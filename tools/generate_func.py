#!/usr/bin/env python3
"""Regenerate the TA-Lib wrappers from ta_func.h.

Usage: python3 tools/generate_func.py [path/to/ta_func.h]

Writes src/func.zig (batch functions) and src/stream.zig (streaming types),
and replaces the alias block between the BEGIN/END GENERATED markers in
src/root.zig; the hand-written code around it is left alone.
"""

import os
import re
import sys

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
BEGIN = '// BEGIN GENERATED FUNCTIONS (tools/generate_func.py)\n'
END = '// END GENERATED FUNCTIONS\n'
HEADER = '// Generated by tools/generate_func.py from ta_func.h; do not edit.\n'


def find_header():
    if len(sys.argv) > 1:
        return sys.argv[1]
    for prefix in ('/opt/homebrew', '/usr/local', '/usr'):
        path = os.path.join(prefix, 'include', 'ta-lib', 'ta_func.h')
        if os.path.exists(path):
            return path
    sys.exit('ta_func.h not found; pass its path as an argument')


def cleanup(name):
    if name.startswith('in'):
        return name[2:].lower()
    if name.startswith('optIn'):
        return name[5:].lower()
    return name.lower()


def split_args(body):
    body = re.sub(r'/\*.*?\*/', '', body, flags=re.S)
    return [' '.join(a.split()) for a in body.split(',')]


def parse(header):
    text = open(header).read()
    funcs = []
    pattern = re.compile(r'TA_LIB_API TA_RetCode TA_([A-Z0-9_]+)\(\s*int\s+startIdx,(.*?)\);', re.S)
    for m in pattern.finditer(text):
        name = m.group(1)
        if name.startswith('S_'):
            continue
        desc = re.search(r'\* TA_%s - (.*)' % re.escape(name), text[:m.start()].rsplit('/*', 1)[-1])
        args = split_args(m.group(2))
        assert args[0] == 'int endIdx', (name, args)
        inputs, opts, outputs = [], [], []
        for arg in args[1:]:
            ctype, var = arg.rsplit(' ', 1)
            if var in ('*outBegIdx', '*outNBElement'):
                continue
            if var.startswith('in'):
                assert ctype == 'const double' and var.endswith('[]'), (name, arg)
                inputs.append(cleanup(var[:-2]))
            elif var.startswith('optIn'):
                ztype = {'int': 'i32', 'double': 'f64', 'TA_MAType': 'MAType'}[ctype]
                opts.append((cleanup(var), ztype))
            elif var.startswith('out'):
                assert var.endswith('[]') and ctype in ('double', 'int'), (name, arg)
                field = var[3:-2]
                is_index = ctype == 'int' and ('INDEX' in name or field.endswith('Idx'))
                outputs.append((field.lower(), 'f64' if ctype == 'double' else 'i32', is_index))
            else:
                assert False, (name, arg)
        assert inputs and outputs, name
        check_stream(text, name, inputs, opts, outputs)
        funcs.append((name, desc.group(1).strip() if desc else None, inputs, opts, outputs))
    return funcs


def check_stream(text, name, inputs, opts, outputs):
    """Assert the streaming entry points take the batch function's arguments."""
    def args_of(suffix):
        m = re.search(r'TA_LIB_API TA_RetCode TA_%s_%s\((.*?)\);' % (name, suffix), text, re.S)
        assert m, (name, suffix)
        return [a.rsplit(' ', 1)[-1].lstrip('*').rstrip('[]') for a in split_args(m.group(1))]
    ins = ['in' + i for i in inputs]
    outs = ['out' + o for o, _, _ in outputs]
    opt_names = [o for o, _ in opts]
    for suffix, expected in (('Open', ['stream'] + ins + ['historyLen'] + opt_names + outs),
                             ('Update', ['stream'] + ins + outs),
                             ('Peek', ['stream'] + ins + outs),
                             ('Value', ['stream'] + outs)):
        got = [cleanup(a) if a.startswith('optIn') else a.lower() for a in args_of(suffix)]
        assert got == [e.lower() for e in expected], (name, suffix, got, expected)


def ret_type(outputs, indent=''):
    if len(outputs) == 1:
        return '[]%s' % outputs[0][1]
    return 'struct {\n%s%s}' % (''.join('%s    %s: []%s,\n' % (indent, f, t) for f, t, _ in outputs), indent)


def make_array(t):
    return 'makeDoubleArray' if t == 'f64' else 'makeIntArray'


def c_opts(opts):
    return ['@backingInt(%s)' % o if t == 'MAType' else o for o, t in opts]


def gen_prologue(w, name, inputs, opts, outputs, ind):
    """Length/NaN/lookback checks and output arrays, shared by batch and openAndFill."""
    n = len(inputs)
    if n == 1:
        w(ind + 'const length = %s.len;' % inputs[0])
    else:
        w(ind + 'const length = try checkLength%d(%s);' % (n, ', '.join(inputs)))


def gen_arrays(w, name, inputs, opts, outputs, ind):
    w(ind + 'const begidx = checkBegIdx%d(length, %s);' % (len(inputs), ', '.join(inputs)))
    w(ind + 'const lookback = begidx + try checkLookback(c.TA_%s_Lookback(%s));' % (name, ', '.join(c_opts(opts))))
    w(ind + 'const outidx = @min(lookback, length);')
    for f, t, _ in outputs:
        w(ind + 'var out%s = try %s(allocator, length, lookback);' % (f, make_array(t)))
        w(ind + 'errdefer allocator.free(out%s);' % f)


def gen_shift_arrays(w, outputs, ind):
    for f, _, is_index in outputs:
        if is_index:
            w(ind + 'for (outidx..length) |i| {')
            w(ind + '    out%s[i] += @intCast(begidx);' % f)
            w(ind + '}')


def gen_func(name, desc, inputs, opts, outputs):
    lines = []
    w = lines.append
    params = ''.join(', %s: []const f64' % i for i in inputs)
    params += ''.join(', %s: %s' % o for o in opts)
    if desc:
        w('/// %s' % desc)
    w('pub fn %s(allocator: std.mem.Allocator%s) !%s {' % (name, params, ret_type(outputs)))
    w('    var outbegidx: i32 = undefined;')
    w('    var outnbelement: i32 = undefined;')
    gen_prologue(w, name, inputs, opts, outputs, '    ')
    empty = lambda t: 'try %s(allocator, 0, 0)' % make_array(t)
    if len(outputs) == 1:
        w('    if (length == 0) return %s;' % empty(outputs[0][1]))
    else:
        w('    if (length == 0) return .{')
        for f, t, _ in outputs:
            w('        .%s = %s,' % (f, empty(t)))
        w('    };')
    gen_arrays(w, name, inputs, opts, outputs, '    ')
    w('    const endidx = length - begidx - 1;')
    call = ['0', '@intCast(endidx)']
    call += ['%s[begidx..].ptr' % i for i in inputs]
    call += c_opts(opts)
    call += ['&outbegidx', '&outnbelement']
    call += ['out%s[outidx..].ptr' % f for f, _, _ in outputs]
    w('    const retCode = c.TA_%s(%s);' % (name, ', '.join(call)))
    w('    try convertRetCode(retCode);')
    gen_shift_arrays(w, outputs, '    ')
    if len(outputs) == 1:
        w('    return out%s;' % outputs[0][0])
    else:
        w('    return .{')
        for f, _, _ in outputs:
            w('        .%s = out%s,' % (f, f))
        w('    };')
    w('}')
    return '\n'.join(lines) + '\n'


def gen_stream(name, desc, inputs, opts, outputs):
    lines = []
    w = lines.append
    handle = 'c.TA_%s_Stream' % name
    array_params = ''.join(', %s: []const f64' % i for i in inputs)
    opt_params = ''.join(', %s: %s' % o for o in opts)
    bar_params = ''.join(', %s: f64' % i for i in inputs)
    single = len(outputs) == 1
    out_type = outputs[0][1] if single else 'Output'
    out_ptrs = ', '.join('&out%s' % f for f, _, _ in outputs)

    def declare_outs(ind):
        for f, t, _ in outputs:
            w(ind + 'var out%s: %s = undefined;' % (f, t))

    def return_outs(ind):
        shifted = lambda f, is_index: 'out%s + self.begidx' % f if is_index else 'out%s' % f
        if single:
            w(ind + 'return %s;' % shifted(outputs[0][0], outputs[0][2]))
        else:
            w(ind + 'return .{')
            for f, _, is_index in outputs:
                w(ind + '    .%s = %s,' % (f, shifted(f, is_index)))
            w(ind + '};')

    if desc:
        w('/// %s' % desc)
    w('pub const %s = struct {' % name)
    w('    handle: *%s,' % handle)
    w('    begidx: i32,')
    w('')
    if not single:
        w('    pub const Output = struct {')
        for f, t, _ in outputs:
            w('        %s: %s,' % (f, t))
        w('    };')
        w('')

    w('    /// Warm up on the history (leading NaN bars are skipped) and start a stream.')
    w('    pub fn init(%s%s) !%s {' % (array_params[2:], opt_params, name))
    gen_prologue(w, name, inputs, opts, outputs, '        ')
    w('        if (length == 0) return TAError.InsufficientHistory;')
    w('        const begidx = checkBegIdx%d(length, %s);' % (len(inputs), ', '.join(inputs)))
    w('        var handle: ?*%s = null;' % handle)
    declare_outs('        ')
    call = ['&handle'] + ['%s[begidx..].ptr' % i for i in inputs] + ['@intCast(length - begidx)'] + c_opts(opts)
    w('        try convertRetCode(c.TA_%s_Open(%s, %s));' % (name, ', '.join(call), out_ptrs))
    w('        return .{ .handle = handle.?, .begidx = @intCast(begidx) };')
    w('    }')
    w('')

    w('    /// Like `init`, but also returns the batch output over the history.')
    fill_ret = 'struct {\n        stream: %s,\n%s    }' % (
        name, ''.join('        %s: []%s,\n' % (f, t) for f, t, _ in outputs))
    w('    pub fn initAndFill(allocator: std.mem.Allocator%s%s) !%s {' % (array_params, opt_params, fill_ret))
    w('        var outbegidx: i32 = undefined;')
    w('        var outnbelement: i32 = undefined;')
    gen_prologue(w, name, inputs, opts, outputs, '        ')
    w('        if (length == 0) return TAError.InsufficientHistory;')
    gen_arrays(w, name, inputs, opts, outputs, '        ')
    w('        var handle: ?*%s = null;' % handle)
    call = ['&handle'] + ['%s[begidx..].ptr' % i for i in inputs] + ['@intCast(length - begidx)'] + c_opts(opts)
    call += ['&outbegidx', '&outnbelement'] + ['out%s[outidx..].ptr' % f for f, _, _ in outputs]
    w('        try convertRetCode(c.TA_%s_OpenAndFill(%s));' % (name, ', '.join(call)))
    gen_shift_arrays(w, outputs, '        ')
    w('        return .{')
    w('            .stream = .{ .handle = handle.?, .begidx = @intCast(begidx) },')
    for f, _, _ in outputs:
        w('            .%s = out%s,' % (f, f))
    w('        };')
    w('    }')
    w('')

    w('    /// Commit one closed bar and return its output.')
    w('    pub fn update(self: *%s%s) TAError!%s {' % (name, bar_params, out_type))
    declare_outs('        ')
    w('        try convertRetCode(c.TA_%s_Update(self.handle, %s, %s));' % (name, ', '.join(inputs), out_ptrs))
    return_outs('        ')
    w('    }')
    w('')

    w('    /// Return what `update` would for this bar, without committing it.')
    w('    pub fn peek(self: *const %s%s) TAError!%s {' % (name, bar_params, out_type))
    declare_outs('        ')
    w('        try convertRetCode(c.TA_%s_Peek(self.handle, %s, %s));' % (name, ', '.join(inputs), out_ptrs))
    return_outs('        ')
    w('    }')
    w('')

    w('    /// The output at the last bar the stream counted.')
    w('    pub fn value(self: *const %s) TAError!%s {' % (name, out_type))
    declare_outs('        ')
    w('        try convertRetCode(c.TA_%s_Value(self.handle, %s));' % (name, out_ptrs))
    return_outs('        ')
    w('    }')
    w('')

    w('    /// The bars this stream has an output for, in the input series\' coordinates.')
    w('    pub fn outRange(self: *const %s) TAError!OutRange {' % name)
    w('        var outbegidx: i32 = undefined;')
    w('        var outnbelement: i32 = undefined;')
    w('        try convertRetCode(c.TA_%s_OutRange(self.handle, &outbegidx, &outnbelement));' % name)
    w('        return .{ .begidx = @intCast(outbegidx + self.begidx), .nbelement = @intCast(outnbelement) };')
    w('    }')
    w('')

    w('    /// Count one bar the stream was not fed; `value` keeps the previous output.')
    w('    pub fn advance(self: *%s) TAError!void {' % name)
    w('        try convertRetCode(c.TA_%s_Advance(self.handle));' % name)
    w('    }')
    w('')

    w('    /// Fork the stream; both must be released with `deinit`.')
    w('    pub fn clone(self: *const %s) TAError!%s {' % (name, name))
    w('        var handle: ?*%s = null;' % handle)
    w('        try convertRetCode(c.TA_%s_Clone(self.handle, &handle));' % name)
    w('        return .{ .handle = handle.?, .begidx = self.begidx };')
    w('    }')
    w('')

    w('    pub fn deinit(self: *%s) void {' % name)
    w('        _ = c.TA_%s_Close(self.handle);' % name)
    w('        self.* = undefined;')
    w('    }')
    w('};')
    return '\n'.join(lines) + '\n'


IMPORTS = '''const std = @import("std");
const c = @import("c");
const common = @import("common.zig");

const MAType = common.MAType;
const TAError = common.TAError;
const convertRetCode = common.convertRetCode;
const checkLength2 = common.checkLength2;
const checkLength3 = common.checkLength3;
const checkLength4 = common.checkLength4;
const checkBegIdx1 = common.checkBegIdx1;
const checkBegIdx2 = common.checkBegIdx2;
const checkBegIdx3 = common.checkBegIdx3;
const checkBegIdx4 = common.checkBegIdx4;
const checkLookback = common.checkLookback;
const makeDoubleArray = common.makeDoubleArray;
const makeIntArray = common.makeIntArray;
'''

STREAM_DOC = '''//! Streaming API: evaluate an indicator one bar at a time.
//!
//! `init` warms a stream up on some history; `update` then commits each new
//! closed bar and returns its output, matching what the batch function
//! returns over the same series. Every opened (or cloned) stream must be released
//! with `deinit`. A stream is not safe to use from several threads at once.

'''

STREAM_TYPES = '''
/// The bars a stream has an output for: [begidx, begidx + nbelement).
pub const OutRange = struct {
    begidx: usize,
    nbelement: usize,
};
'''


def main():
    funcs = parse(find_header())

    with open(os.path.join(SRC, 'func.zig'), 'w') as fp:
        fp.write(HEADER + '\n' + IMPORTS + '\n' + '\n'.join(gen_func(*f) for f in funcs))

    with open(os.path.join(SRC, 'stream.zig'), 'w') as fp:
        fp.write(STREAM_DOC + HEADER + '\n' + IMPORTS + STREAM_TYPES + '\n' + '\n'.join(gen_stream(*f) for f in funcs))

    root = os.path.join(SRC, 'root.zig')
    src = open(root).read()
    head, rest = src.split(BEGIN)
    _, tail = rest.split(END)
    aliases = ''.join('pub const %s = func.%s;\n' % (f[0], f[0]) for f in funcs)
    with open(root, 'w') as fp:
        fp.write(head + BEGIN + aliases + END + tail)

    print('generated %d functions' % len(funcs))


if __name__ == '__main__':
    main()
